import * as React from "react"

import { cn } from "@/lib/utils"

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        "group/card flex flex-col gap-[var(--card-spacing,1rem)] overflow-hidden rounded-[var(--radius-card)] bg-surface py-[var(--card-spacing,1rem)] text-text-primary border border-border shadow-[var(--shadow-soft)] transition-shadow hover:shadow-[var(--shadow-hover)]",
        className
      )}
      {...props}
    />
  )
}

